CREATE DATABASE IF NOT EXISTS GD_Hoteis;
USE GD_Hoteis;

CREATE TABLE Categoria (
    id_categoria INT NOT NULL AUTO_INCREMENT,
    nome VARCHAR(10) NOT NULL,
    valor_diaria DECIMAL(10, 2) NOT NULL, 
    PRIMARY KEY (id_categoria)
);

CREATE TABLE Pagamento (
    id_pagamento INT NOT NULL AUTO_INCREMENT,
    valor DECIMAL(10, 2) NOT NULL,
    tipo_transacao VARCHAR(10) NOT NULL,
    PRIMARY KEY (id_pagamento)
);

CREATE TABLE Funcionario (
    id_funcionario INT NOT NULL AUTO_INCREMENT,
    nome VARCHAR(50) NOT NULL,
    numero_tel VARCHAR(11) NOT NULL,
    cargo VARCHAR(30) NOT NULL,         
    salario DECIMAL(10, 2) NOT NULL,     
    PRIMARY KEY (id_funcionario)
);

CREATE TABLE Cliente (
    CPF VARCHAR(12) NOT NULL,
    numero VARCHAR(12) NOT NULL,
    email VARCHAR(100) NOT NULL,        
    Status_Financeiro VARCHAR(10) NOT NULL,
    nome VARCHAR(50) NOT NULL,
    id_pagamento INT, 
    PRIMARY KEY (CPF),
    FOREIGN KEY (id_pagamento) REFERENCES Pagamento(id_pagamento)
);

CREATE TABLE Quarto (
    id_quarto INT NOT NULL AUTO_INCREMENT,
    Status VARCHAR(10) NOT NULL,
    Andar VARCHAR(2) NOT NULL,
    id_categoria INT NOT NULL,
    PRIMARY KEY (id_quarto),
    FOREIGN KEY (id_categoria) REFERENCES Categoria(id_categoria)
);

CREATE TABLE Reserva (
    id_reserva INT NOT NULL AUTO_INCREMENT,
    Data_entrada DATE NOT NULL, 
    Data_Saida DATE NOT NULL, 
    id_quarto INT NOT NULL,
    CPF VARCHAR(12) NOT NULL, -- Corrigido de 11 para 12 para coincidir com a tabela Cliente
    PRIMARY KEY (id_reserva),
    FOREIGN KEY (id_quarto) REFERENCES Quarto(id_quarto),
    FOREIGN KEY (CPF) REFERENCES Cliente(CPF)
);

CREATE TABLE Servico (
    id_servico INT NOT NULL AUTO_INCREMENT,
    Data_hora DATETIME NOT NULL, 
    tipo_servico VARCHAR(20) NOT NULL,
    id_quarto INT NOT NULL,
    id_funcionario INT NOT NULL,
    PRIMARY KEY (id_servico),
    FOREIGN KEY (id_quarto) REFERENCES Quarto(id_quarto),
    FOREIGN KEY (id_funcionario) REFERENCES Funcionario(id_funcionario)
);

CREATE TABLE Produto (
    id_produto INT NOT NULL AUTO_INCREMENT,
    nome VARCHAR(15) NOT NULL,
    preco_venda DECIMAL(10, 2) NOT NULL,
    estoque INT NOT NULL,
    PRIMARY KEY (id_produto)
);

CREATE TABLE Venda (
    id_venda INT NOT NULL AUTO_INCREMENT,
    quantidade INT NOT NULL,
    Data_Hora DATETIME NOT NULL,
    Subtotal DECIMAL(10, 2) NOT NULL,
    id_reserva INT NOT NULL,
    id_produto INT NOT NULL,
    PRIMARY KEY (id_venda),
    FOREIGN KEY (id_reserva) REFERENCES Reserva(id_reserva),
    FOREIGN KEY (id_produto) REFERENCES Produto(id_produto)
);

